-- ── Manual Payments ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS manual_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number TEXT,
  amount INTEGER NOT NULL,
  payment_method TEXT DEFAULT 'bank' CHECK (payment_method IN ('bank','telebirr','chapa','cash')),
  bank_name TEXT DEFAULT '',
  account_name TEXT DEFAULT '',
  account_number TEXT DEFAULT '',
  transaction_id TEXT DEFAULT '',
  receipt_url TEXT DEFAULT '',
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','verified','rejected','refunded')),
  verified_by BIGINT,
  verified_at TIMESTAMPTZ,
  customer_telegram_id BIGINT,
  customer_name TEXT DEFAULT '',
  customer_phone TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Bank Accounts (for manual payments) ────────────────────────────
CREATE TABLE IF NOT EXISTS bank_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bank_name TEXT NOT NULL,
  account_name TEXT NOT NULL,
  account_number TEXT NOT NULL,
  branch TEXT DEFAULT '',
  active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Vendor Payouts ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS payouts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT,
  vendor_name TEXT DEFAULT '',
  amount INTEGER NOT NULL,
  commission_deducted INTEGER DEFAULT 0,
  payment_method TEXT DEFAULT 'telebirr' CHECK (payment_method IN ('bank','telebirr','chapa')),
  account_name TEXT DEFAULT '',
  account_number TEXT DEFAULT '',
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','processing','paid','failed','cancelled')),
  period_start TIMESTAMPTZ,
  period_end TIMESTAMPTZ,
  paid_at TIMESTAMPTZ,
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Returns / Refunds ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number TEXT NOT NULL,
  product_id BIGINT,
  product_name TEXT DEFAULT '',
  quantity INTEGER DEFAULT 1,
  reason TEXT DEFAULT '',
  description TEXT DEFAULT '',
  images JSONB DEFAULT '[]'::jsonb,
  refund_amount INTEGER DEFAULT 0,
  refund_method TEXT DEFAULT 'original' CHECK (refund_method IN ('original','bank','telebirr','store_credit')),
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','refunded','completed')),
  customer_telegram_id BIGINT,
  customer_name TEXT DEFAULT '',
  customer_phone TEXT DEFAULT '',
  approved_by BIGINT,
  approved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Order Fulfillments ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS order_fulfillments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number TEXT NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','processing','packed','shipped','delivered','cancelled')),
  items JSONB DEFAULT '[]'::jsonb,
  tracking_code TEXT DEFAULT '',
  carrier TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  packed_by BIGINT,
  packed_at TIMESTAMPTZ,
  shipped_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Abandoned Carts ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS abandoned_carts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id BIGINT,
  customer_name TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  items JSONB DEFAULT '[]'::jsonb,
  total INTEGER DEFAULT 0,
  recovery_status TEXT DEFAULT 'new' CHECK (recovery_status IN ('new','contacted','recovered','lost')),
  recovery_message_id BIGINT,
  recovered_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Coupon Usage Analytics ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS coupon_analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coupon_code TEXT NOT NULL,
  discount_amount INTEGER DEFAULT 0,
  order_number TEXT,
  customer_telegram_id BIGINT,
  customer_name TEXT DEFAULT '',
  used_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Admin Roles ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS admin_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  permissions JSONB DEFAULT '[]'::jsonb,
  description TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id BIGINT UNIQUE,
  username TEXT DEFAULT '',
  role_id BIGINT REFERENCES admin_roles(id),
  permissions JSONB DEFAULT '[]'::jsonb,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Activity Log ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  entity_type TEXT DEFAULT '',
  entity_id TEXT DEFAULT '',
  admin_id BIGINT,
  admin_name TEXT DEFAULT '',
  details JSONB DEFAULT '{}'::jsonb,
  ip_address TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Accounting / Audit Trail ──────────────────────────────────────
CREATE TABLE IF NOT EXISTS accounting_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('revenue','expense','commission','payout','refund','adjustment')),
  description TEXT DEFAULT '',
  amount INTEGER NOT NULL,
  balance_before INTEGER DEFAULT 0,
  balance_after INTEGER DEFAULT 0,
  reference_type TEXT DEFAULT '',
  reference_id TEXT DEFAULT '',
  created_by BIGINT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Promotions ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS promotions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT DEFAULT 'percentage' CHECK (type IN ('percentage','fixed','bogo','free_shipping')),
  value INTEGER DEFAULT 0,
  min_order INTEGER DEFAULT 0,
  max_discount INTEGER DEFAULT 0,
  starts_at TIMESTAMPTZ,
  ends_at TIMESTAMPTZ,
  usage_limit INTEGER DEFAULT 0,
  used_count INTEGER DEFAULT 0,
  applicable_products JSONB DEFAULT '[]'::jsonb,
  applicable_categories JSONB DEFAULT '[]'::jsonb,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── SLA Config ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS sla_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  metric TEXT DEFAULT '',
  threshold_minutes INTEGER DEFAULT 30,
  warning_minutes INTEGER DEFAULT 25,
  escalation_minutes INTEGER DEFAULT 60,
  notify_roles JSONB DEFAULT '["admin"]'::jsonb,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sla_alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sla_config_id BIGINT REFERENCES sla_config(id),
  entity_type TEXT DEFAULT '',
  entity_id TEXT DEFAULT '',
  status TEXT DEFAULT 'open' CHECK (status IN ('open','acknowledged','resolved')),
  acknowledged_by BIGINT,
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Notifications (persistent) ─────────────────────────────────────
