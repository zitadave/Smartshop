CREATE INDEX IF NOT EXISTS idx_returns_order ON returns(order_number);
CREATE INDEX IF NOT EXISTS idx_returns_status ON returns(status);
CREATE INDEX IF NOT EXISTS idx_of_order ON order_fulfillments(order_number);
CREATE INDEX IF NOT EXISTS idx_ac_status ON abandoned_carts(recovery_status);
CREATE INDEX IF NOT EXISTS idx_ca_coupon ON coupon_analytics(coupon_code);
CREATE INDEX IF NOT EXISTS idx_al_action ON activity_logs(action);
CREATE INDEX IF NOT EXISTS idx_al_created ON activity_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_ae_type ON accounting_entries(entry_type);
CREATE INDEX IF NOT EXISTS idx_ae_created ON accounting_entries(created_at);
