-- ── Group Buying (ማህበር ግዢ) ──────────────────────────────
CREATE TABLE IF NOT EXISTS group_deals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT REFERENCES products(id),
  product_name TEXT NOT NULL,
  product_image TEXT DEFAULT '',
  regular_price INTEGER NOT NULL,
  group_price INTEGER NOT NULL,
  min_members INTEGER DEFAULT 2,
  max_members INTEGER DEFAULT 10,
  current_members INTEGER DEFAULT 1,
  creator_telegram_id BIGINT NOT NULL,
  creator_name TEXT DEFAULT '',
  share_token TEXT UNIQUE NOT NULL,
  status TEXT DEFAULT 'open' CHECK (status IN ('open','active','fulfilled','expired')),
  expires_at TIMESTAMPTZ DEFAULT NOW() + INTERVAL '48 hours',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS group_deal_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_deal_id BIGINT REFERENCES group_deals(id) ON DELETE CASCADE,
  telegram_id BIGINT NOT NULL,
  full_name TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  quantity INTEGER DEFAULT 1,
  paid BOOLEAN DEFAULT false,
  joined_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Gift Registry (የሰርግ ስጦታ መዝገብ) ─────────────────────────
CREATE TABLE IF NOT EXISTS gift_registries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  couple_name TEXT NOT NULL,
  couple_amharic_name TEXT DEFAULT '',
  wedding_date TEXT NOT NULL,
  wedding_location TEXT DEFAULT '',
  message TEXT DEFAULT '',
  share_token TEXT UNIQUE NOT NULL,
  creator_telegram_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS registry_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registry_id BIGINT REFERENCES gift_registries(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id),
  product_name TEXT NOT NULL,
  product_image TEXT DEFAULT '',
  price INTEGER NOT NULL,
  quantity INTEGER DEFAULT 1,
  purchased INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS registry_purchases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registry_item_id BIGINT REFERENCES registry_items(id) ON DELETE CASCADE,
  buyer_name TEXT NOT NULL,
  buyer_telegram_id BIGINT,
  quantity INTEGER DEFAULT 1,
  amount INTEGER NOT NULL,
  message TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Subscriptions (የደንበኝነት ምርቶች) ─────────────────────────
CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id BIGINT NOT NULL,
  product_id BIGINT REFERENCES products(id),
  product_name TEXT NOT NULL,
  product_image TEXT DEFAULT '',
  quantity INTEGER DEFAULT 1,
  frequency TEXT NOT NULL CHECK (frequency IN ('daily','weekly','monthly')),
  price INTEGER NOT NULL,
  next_delivery TIMESTAMPTZ NOT NULL,
  status TEXT DEFAULT 'active' CHECK (status IN ('active','paused','cancelled')),
  delivery_address TEXT DEFAULT '',
  delivery_note TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ── Reseller Program ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS referral_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_telegram_id BIGINT NOT NULL,
  referral_code TEXT NOT NULL,
  referred_telegram_id BIGINT,
  product_id BIGINT,
  order_number TEXT,
  amount INTEGER DEFAULT 0,
  commission INTEGER DEFAULT 0,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','paid','cancelled')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

