CREATE INDEX IF NOT EXISTS idx_gd_status ON group_deals(status);
CREATE INDEX IF NOT EXISTS idx_gd_share ON group_deals(share_token);
CREATE INDEX IF NOT EXISTS idx_gd_product ON group_deals(product_id);
CREATE INDEX IF NOT EXISTS idx_gdm_deal ON group_deal_members(group_deal_id);
CREATE INDEX IF NOT EXISTS idx_gr_share ON gift_registries(share_token);
CREATE INDEX IF NOT EXISTS idx_ri_registry ON registry_items(registry_id);
CREATE INDEX IF NOT EXISTS idx_subs_user ON subscriptions(telegram_id);
CREATE INDEX IF NOT EXISTS idx_subs_next ON subscriptions(next_delivery) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_rl_referrer ON referral_logs(referrer_telegram_id);
CREATE INDEX IF NOT EXISTS idx_rl_code ON referral_logs(referral_code);

