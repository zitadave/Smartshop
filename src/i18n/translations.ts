/**
 * High-performance O(1) translation lookup with fallback chain:
 * active language -> English -> raw key string.
 */
export function t(key: string, lang: Language = 'am'): string {
  const dict = (translations[lang] || translations.am) as Record<string, string>;
  const enDict = translations.en as Record<string, string>;
  return dict[key] || enDict[key] || key;
}

